#pragma once
// ============================================================
//  时间同步（腰端）— 开机一次性 NTP（v0.6，腕端 OLED 时钟源）
//
//  流程：连 WiFi(限时) → configTime(UTC) → 等 time() 有效
//        → 断开 WiFi、信道还给 ESP-NOW → 之后本地走时
//  与按需推送共用"连 WiFi→干活→回 ch6"射频模式，报警主链路不受影响。
//
//  使用方式：在独立低优先级任务里调 net_time_sync()（内部限时，失败快速返回）；
//  之后任意时刻 net_time_epoch() 取当前 UTC 秒（未同步=0），捎带进 PKT_ACK。
// ============================================================
#include <Arduino.h>

bool net_time_sync(void);       // 阻塞式一次性同步（限时；热点没开/超时则放弃）

uint32_t net_time_epoch(void);  // 当前 UTC 秒（0=未同步；millis 锚点外推，无需再联网）
