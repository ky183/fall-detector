#pragma once
// ============================================================
//  按钮输入（腕端）— 交互按钮
//  单按钮两种语义：
//    短按（<1s）= OLED 交互/翻页（骨架阶段：事件计数，翻页 TODO）
//    长按（≥1s）= 模拟跌倒（ENABLE_FALL_DETECT=0 时调试报警链路）
//  取消报警按钮在腰端，不在腕端
//  内置去抖（连续 2 次采样确认电平变化，约 40ms）
//  长按在按住期间即触发（无需松手），触发一次后需松开重按
// ============================================================
#include <Arduino.h>

enum ButtonEvent {
    BTN_NONE  = 0,   // 无事件
    BTN_SHORT = 1,   // 短按（松开时判定）
    BTN_LONG  = 2,   // 长按（按住满 1s 即判定）
};

void button_init();               // 配置引脚上拉
ButtonEvent button_poll();        // 周期调用（BUTTON_POLL_MS），返回本次事件（最多一个）
